"""Deploy Ulat to Modal and manage the Telegram webhook (see deploy/README.md).

    uv run python -m app.deploy secrets      --target staging   # .env -> Modal secret, no echo
    uv run python -m app.deploy seed-assets  --target staging   # demo photos + model cache
    uv run python -m app.deploy deploy       --target staging   # the committed HEAD
    uv run python -m app.deploy webhook set  --target staging   # info | set | delete
    uv run python -m app.deploy snapshots    --target staging
    uv run python -m app.deploy restore      --target staging app-20261030T101500000000Z.db
    uv run python -m app.deploy logs | stop  --target staging

Production needs --yes on every command that changes it. Secret values are read from .env and
handed to Modal through a private temp file; they are never printed, logged or put on a command
line. Generated values (webhook secret, passcode, session secret) are appended to .env, which is
git-ignored, and only their names are printed.
"""

import argparse
import asyncio
import json
import os
import secrets
import shutil
import subprocess
import sys
import tarfile
import tempfile
from collections.abc import Callable, Sequence
from pathlib import Path

from dotenv import dotenv_values
from telegram import Bot

from app.bot import ALLOWED_UPDATES, _with_retries
from app.deploy_targets import (
    DEMO_IMAGES_SUBDIR,
    MODEL_CACHE_SUBDIR,
    REQUIRED_KEYS,
    SNAPSHOT_SUBDIR,
    TARGETS,
    Target,
)
from app.snapshots import RESTORE_REQUEST, SNAPSHOT_PREFIX, SNAPSHOT_SUFFIX
from app.telegram_webhook import webhook_path

REPO_ROOT = Path(__file__).resolve().parent.parent
ENV_FILE = REPO_ROOT / ".env"
MODAL_ENTRYPOINT = "deploy.modal_app"


class DeployError(RuntimeError):
    pass


def generate_value(env_name: str) -> str:
    """A random value for a generated secret: a passcode an officer can type, hex otherwise."""
    if env_name.endswith("OFFICER_PASSCODE"):
        return secrets.token_urlsafe(15)  # 20 characters
    return secrets.token_hex(32)


def ensure_generated(target: Target, env_file: Path, out: Callable[[str], None] = print) -> None:
    """Append the target's missing generated secrets to .env (values never printed)."""
    values = dotenv_values(env_file) if env_file.exists() else {}
    missing = sorted(name for name in target.generated if not values.get(name))
    if not missing:
        return
    text = env_file.read_text(encoding="utf-8") if env_file.exists() else ""
    lines = [] if not text or text.endswith("\n") else [""]
    lines.append(f"# Generated by `python -m app.deploy secrets --target {target.name}`")
    lines += [f"{name}={generate_value(name)}" for name in missing]
    with env_file.open("a", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")
    os.chmod(env_file, 0o600)
    out(f"added to {env_file.name}: {', '.join(missing)}")


def secret_values(target: Target, env_file: Path) -> dict[str, str]:
    """The target's container secrets from .env; raises naming any required key that is empty."""
    env = dotenv_values(env_file) if env_file.exists() else {}
    values = {key: env.get(source) or "" for key, source in target.sources.items()}
    missing = [f"{key} (.env {target.sources[key]})" for key in REQUIRED_KEYS if not values[key]]
    if missing:
        raise DeployError(f"missing in {env_file.name}: {', '.join(missing)}")
    return {key: value for key, value in values.items() if value}


def modal_bin() -> str:
    found = os.environ.get("MODAL_BIN") or shutil.which("modal")
    if not found:
        raise DeployError("the modal CLI is not installed: pip install modal; modal setup")
    return found


def run_modal(args: Sequence[str], *, check: bool = True, capture: bool = False, **kwargs):
    return subprocess.run(
        [modal_bin(), *args], check=check, capture_output=capture, text=True, **kwargs
    )


def workspace() -> str:
    profiles = json.loads(run_modal(["profile", "list", "--json"], capture=True).stdout)
    for profile in profiles:
        if profile.get("active"):
            return profile["workspace"]
    raise DeployError("no active Modal profile: run modal setup")


def push_secret(target: Target, env_file: Path, out: Callable[[str], None] = print) -> None:
    ensure_generated(target, env_file, out)
    values = secret_values(target, env_file)
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "secret.json"
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            json.dump(values, handle)
        result = run_modal(
            ["secret", "create", "--force", target.secret, "--from-json", str(path)],
            capture=True,
            check=False,
        )
    if result.returncode != 0:
        raise DeployError(f"modal secret create failed (exit {result.returncode})")
    out(f"Modal secret {target.secret}: {', '.join(sorted(values))}")


def export_head(dest: Path) -> str:
    """The committed HEAD (not the working tree) into `dest`; returns its short hash."""
    sha = subprocess.run(
        ["git", "rev-parse", "--short", "HEAD"],
        cwd=REPO_ROOT,
        check=True,
        capture_output=True,
        text=True,
    ).stdout.strip()
    archive = dest / "head.tar"
    subprocess.run(
        ["git", "archive", "--format=tar", "-o", str(archive), "HEAD"], cwd=REPO_ROOT, check=True
    )
    with tarfile.open(archive) as tar:
        tar.extractall(dest / "src", filter="data")
    return sha


def deploy(target: Target, out: Callable[[str], None] = print) -> None:
    dirty = subprocess.run(
        ["git", "status", "--porcelain", "--untracked-files=no"],
        cwd=REPO_ROOT,
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    if dirty:
        out("note: uncommitted changes are not deployed; deploying the committed HEAD")
    space = workspace()
    with tempfile.TemporaryDirectory(prefix="ulat-deploy-") as tmp:
        sha = export_head(Path(tmp))
        env = {**os.environ, "ULAT_TARGET": target.name, "ULAT_WORKSPACE": space}
        # recreate: stop the old container before starting the new one, so there is never a
        # second SQLite writer, and the new one restores the old one's final snapshot.
        run_modal(
            ["deploy", "--strategy", "recreate", "--tag", sha, "-m", MODAL_ENTRYPOINT],
            cwd=Path(tmp) / "src",
            env=env,
        )
    out(f"deployed {sha} to https://{target.host(space)}")


def seed_assets(target: Target, source: Path, out: Callable[[str], None] = print) -> None:
    """Upload the generated demo photos and the model-response cache (both synthetic)."""
    images = source / "images"
    if not images.is_dir():
        raise DeployError(
            f"no demo images in {images}: DATA_DIR=var/demo python -m app.demo images"
        )
    created = run_modal(
        ["volume", "create", "--version", "2", target.volume], check=False, capture=True
    )
    if created.returncode == 0:
        out(f"created volume {target.volume}")
    run_modal(["volume", "put", "--force", target.volume, str(images), f"/{DEMO_IMAGES_SUBDIR}"])
    cache = source / "model_cache"
    if cache.is_dir():
        run_modal(["volume", "put", "--force", target.volume, str(cache), f"/{MODEL_CACHE_SUBDIR}"])
    out(f"uploaded {images} and {cache} to volume {target.volume}")


def restore(target: Target, snapshot: str, out: Callable[[str], None] = print) -> None:
    """Ask the next container to restore `snapshot`, then restart the app."""
    if (
        not (snapshot.startswith(SNAPSHOT_PREFIX) and snapshot.endswith(SNAPSHOT_SUFFIX))
        or "/" in snapshot
    ):
        raise DeployError(f"not a snapshot name: {snapshot} (see the snapshots command)")
    with tempfile.TemporaryDirectory() as tmp:
        request = Path(tmp) / RESTORE_REQUEST
        request.write_text(snapshot, encoding="utf-8")
        run_modal(
            [
                "volume",
                "put",
                "--force",
                target.volume,
                str(request),
                f"/{SNAPSHOT_SUBDIR}/{RESTORE_REQUEST}",
            ]
        )
    run_modal(["app", "rollover", "--strategy", "recreate", target.app])
    out(f"{target.app} restarted; it restores {snapshot} (the replaced database is kept)")


# -- Telegram webhook --


def bot_for(target: Target, env_file: Path) -> tuple[Bot, str]:
    env = dotenv_values(env_file) if env_file.exists() else {}
    token = env.get(target.sources["TELEGRAM_BOT_TOKEN"])
    secret = env.get(target.sources["TELEGRAM_WEBHOOK_SECRET"])
    if not token or not secret:
        raise DeployError(
            f"set {target.sources['TELEGRAM_BOT_TOKEN']} in .env and run the secrets command first"
        )
    return Bot(token), secret


def masked(url: str) -> str:
    """A webhook URL without its secret path segment."""
    if not url:
        return "(none)"
    head, _, tail = url.rpartition("/")
    return f"{head}/{tail[:4]}…" if tail else url


async def webhook(
    action: str, target: Target, bot: Bot, secret: str, host: str, out: Callable[[str], None]
) -> None:
    async with bot:
        if action == "set":
            url = f"https://{host}{webhook_path(secret)}"
            await _with_retries(
                lambda: bot.set_webhook(
                    url,
                    secret_token=secret,
                    allowed_updates=ALLOWED_UPDATES,
                    drop_pending_updates=False,
                    # One delivery at a time keeps updates in order, as polling does (an album,
                    # a caption right after its photo); the route only queues, so it is fast.
                    max_connections=1,
                )
            )
            out(f"webhook set for {target.name}: {masked(url)}")
        elif action == "delete":
            await _with_retries(lambda: bot.delete_webhook(drop_pending_updates=False))
            out(f"webhook deleted for {target.name}; pending updates are kept for polling")
        info = await _with_retries(bot.get_webhook_info)
        out(f"url: {masked(info.url)}")
        out(f"pending updates: {info.pending_update_count}")
        if info.last_error_date:
            out(f"last error: {info.last_error_date:%Y-%m-%d %H:%M %Z} {info.last_error_message}")
        else:
            out("last error: none")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Deploy Ulat to Modal (see deploy/README.md).")
    commands = parser.add_subparsers(dest="command", required=True)

    def command(name: str, help_text: str) -> argparse.ArgumentParser:
        sub = commands.add_parser(name, help=help_text)
        sub.add_argument("--target", choices=sorted(TARGETS), required=True)
        sub.add_argument("--yes", action="store_true", help="confirm a production change")
        return sub

    command("secrets", "create or update the target's Modal secret from .env")
    assets = command("seed-assets", "upload the demo photos and model cache to the volume")
    assets.add_argument("--from", dest="source", type=Path, default=REPO_ROOT / "var" / "demo")
    command("deploy", "deploy the committed HEAD")
    hook = command("webhook", "show, set or delete the bot's webhook")
    hook.add_argument("action", choices=("info", "set", "delete"))
    command("snapshots", "list the database snapshots on the volume")
    back = command("restore", "restore a snapshot and restart the app")
    back.add_argument("snapshot")
    command("logs", "stream the app's logs")
    command("stop", "stop the app (final snapshot first); deploy again to start it")
    args = parser.parse_args(argv)
    target = TARGETS[args.target]

    read_only = args.command in ("snapshots", "logs") or getattr(args, "action", "") == "info"
    if target.needs_confirmation and not read_only and not args.yes:
        print(f"{args.command} changes {target.name}: run again with --yes", file=sys.stderr)
        return 2
    try:
        if args.command == "secrets":
            push_secret(target, ENV_FILE)
        elif args.command == "seed-assets":
            seed_assets(target, args.source)
        elif args.command == "deploy":
            deploy(target)
        elif args.command == "webhook":
            bot, secret = bot_for(target, ENV_FILE)
            asyncio.run(webhook(args.action, target, bot, secret, target.host(workspace()), print))
        elif args.command == "snapshots":
            run_modal(["volume", "ls", target.volume, f"/{SNAPSHOT_SUBDIR}"])
        elif args.command == "restore":
            restore(target, args.snapshot)
        elif args.command == "logs":
            run_modal(["app", "logs", target.app])
        elif args.command == "stop":
            run_modal(["app", "stop", target.app])
    except DeployError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    except subprocess.CalledProcessError as exc:
        print(f"error: modal exited with {exc.returncode}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
